// Compiles tokens/tokens.json -> src/styles/tokens.css.
// tokens.css is the ONLY file allowed to contain raw colour or length literals (enforced by stylelint).
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url)));
const out = [];
const resolve = (v) =>
  typeof v === 'string' && v.startsWith('{')
    ? `var(--ff-color-${v.slice(1, -1).replace('.', '-')})`
    : v;

out.push('/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */');
out.push(':root {');
for (const [group, scale] of Object.entries(t.color))
  for (const [k, v] of Object.entries(scale)) out.push(`  --ff-color-${group}-${k}: ${v};`);
for (const [k, v] of Object.entries(t.space)) out.push(`  --space-${k}: ${v / 16}rem;`);
for (const [k, v] of Object.entries(t.radius)) out.push(`  --radius-${k}: ${v}px;`);
// Border widths stay in px: 0.5 is a hairline on high-density screens.
for (const [k, v] of Object.entries(t.border)) out.push(`  --border-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.font.family)) out.push(`  --font-${k}: ${v};`);
for (const [k, v] of Object.entries(t.font.size)) out.push(`  --text-${k}: ${v / 16}rem;`);
for (const [k, v] of Object.entries(t.font.weight)) out.push(`  --weight-${k}: ${v};`);
for (const [k, v] of Object.entries(t.font.leading)) out.push(`  --leading-${k}: ${v};`);
for (const [k, v] of Object.entries(t.size)) out.push(`  --size-${k}: ${v / 16}rem;`);
for (const [k, v] of Object.entries(t.motion)) out.push(`  --motion-${k}: ${v};`);
out.push('}');

const theme = (mode) =>
  Object.entries(t.semantic[mode]).map(([k, v]) => `  --color-${k}: ${resolve(v)};`).join('\n');

// Dark is the default (matches the Figma prototype). Light follows the OS unless forced.
out.push(`\n:root, [data-theme='dark'] {\n  color-scheme: dark;\n${theme('dark')}\n}`);
out.push(`\n@media (prefers-color-scheme: light) {\n  :root:not([data-theme='dark']) {\n    color-scheme: light;\n${theme('light').replace(/^/gm, '  ')}\n  }\n}`);
out.push(`\n[data-theme='light'] {\n  color-scheme: light;\n${theme('light')}\n}\n`);

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), out.join('\n'));
console.log('tokens.css written');
